import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const origin=process.env.TRACE_PRODUCTION_URL||'http://127.0.0.1:8795';
const checks=[];
function check(name,value){assert.ok(value,name);checks.push(name);}
const page=await fetch(origin+'/');
const html=await page.text();
check('Anonymous page loads',page.ok);
check('Trace citation identifies authors and contact emails',html.includes('Ryaboy, Michael and Bakour, Yahia')&&html.includes('michael@context.dev')&&html.includes('yahia@context.dev'));
check('Trace and NEEDLE credited separately',html.includes('Copy Trace citation')&&html.includes('Inspiration')&&html.includes('keenableai.github.io/needle'));
check('Private repository linked without source ZIP',html.includes('https://github.com/context-dot-dev/trace-benchmark')&&!html.includes('trace-source.zip'));
for(const path of ['/trace-source.zip','/.env','/.git/config'])check(path+' is not public',(await fetch(origin+path)).status===404);
const response=await fetch(origin+'/api/summary');const summary=await response.json();
check('Live summary loads',response.ok&&summary.schema_version===2&&!('records' in summary));
const params=new URLSearchParams({cohort:'independent',version:summary.version});
const records=await(await fetch(origin+'/api/results?'+params)).json();
check('Query strings and bounded results work',records.version===summary.version&&records.records.length>0&&records.records.length<=8);
const record=records.records[0];
const detail=await(await fetch(origin+'/api/result?'+new URLSearchParams({id:record.id,version:summary.version}))).json();
check('Individual evidence loads',detail.id===record.id);
const unchanged=await fetch(origin+'/api/summary',{headers:{'If-None-Match':response.headers.get('etag')}});
check('Freshness and ETag validation preserved',unchanged.status===304);
const asset=html.match(/src="([^"]+\.js)"/)[1];
check('Bundled app loads',(await fetch(new URL(asset,origin))).ok);
const manifest=summary.runs.find(r=>r.manifest_url)?.manifest_url;
check('Run manifests load',manifest&&(await fetch(new URL(manifest,origin))).ok);
await fs.mkdir('artifacts/production',{recursive:true});
await fs.writeFile('artifacts/production/verification.json',JSON.stringify({passed:true,origin,at:new Date().toISOString(),checks,version:summary.version,lastCompleted:summary.cohorts.independent.lastCompleted},null,2));
console.log(JSON.stringify({passed:true,checks:checks.length,origin}));
