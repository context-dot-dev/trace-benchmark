import React from 'react';
import { createRoot, hydrateRoot } from 'react-dom/client';
import App from './App';
import { validateSummary } from './use-benchmark';
import './styles.css';
import './article.css';
const bootstrap=document.getElementById('trace-summary');
const initialData=bootstrap?validateSummary(JSON.parse(bootstrap.textContent)):null;
const root=document.getElementById('root');
if(root.hasChildNodes())hydrateRoot(root,<App initialData={initialData}/>);
else createRoot(root).render(<App initialData={initialData}/>);
